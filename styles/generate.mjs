// Generates the MapLibre styles of the SmartMet OSM engine.
//
// protomaps-*  The five Protomaps basemap flavors as published.
// versatiles-* VersaTiles themes built for the Protomaps schema, among them
//              Positron and Dark Matter lookalikes (positrino) which are
//              classic backgrounds for data visualization. MIT licensed.
// meteo-*      Backgrounds for meteorological data derived from the Protomaps
//              flavors: only land, water, subtle landcover, borders, major roads
//              and place names, with muted colours which do not compete with
//              the data drawn on top. The background colour is the sea colour
//              so that the polar areas outside Web Mercator look like sea.
//
// The styles are for the Protomaps basemap tile schema (Protomaps daily builds).
// Map design: CC0 (Protomaps), code BSD-3-Clause.
//
// Usage: npm install && node generate.mjs <outputdir>

import { layers, namedFlavor } from "@protomaps/basemaps";
import { protomaps as versatiles } from "@versatiles/style/protomaps";
import fs from "fs";

const out = process.argv[2] ?? ".";
const SOURCE = "protomaps";

function style(name, title, flavor, lang, filter, tune) {
  let ls = layers(SOURCE, flavor, { lang });
  if (filter) ls = ls.filter((l) => filter.includes(l.id));
  if (tune) ls = tune(ls);
  return {
    version: 8,
    name: title,
    metadata: {
      "smartmet:description": `${title}, generated by generate.mjs from @protomaps/basemaps 5.7.2`,
      "smartmet:license": "Map design CC0-1.0 (Protomaps), code BSD-3-Clause",
      "smartmet:schema": "protomaps",
    },
    glyphs: "https://protomaps.github.io/basemaps-assets/fonts/{fontstack}/{range}.pbf",
    sprite: `https://protomaps.github.io/basemaps-assets/sprites/v4/${flavor === undefined ? "light" : name.replace(/^.*-/, "")}`,
    sources: {
      [SOURCE]: { type: "vector", attribution: "© OpenStreetMap contributors" },
    },
    layers: ls,
  };
}

function write(name, doc) {
  fs.writeFileSync(`${out}/${name}.json`, JSON.stringify(doc, null, 1) + "\n");
}

// The published flavors
for (const f of ["light", "dark", "white", "grayscale", "black"])
  write(`protomaps-${f}`, style(`protomaps-${f}`, `Protomaps ${f}`, namedFlavor(f), "en"));

// VersaTiles themes for the Protomaps schema

for (const theme of ["positrino", "positrino-dark", "gray", "gray-dark", "muted", "colorful"]) {
  const doc = versatiles({
    theme,
    urls: { protomaps: "pmtiles://protomaps" },
    projection: "mercator",
    sky: false,
    light: false,
  });
  doc.name = `VersaTiles ${theme}`;
  doc.metadata = {
    ...(doc.metadata ?? {}),
    "smartmet:description": `VersaTiles ${theme} theme for the Protomaps schema, generated by generate.mjs from @versatiles/style 7.0.1`,
    "smartmet:license": "MIT (VersaTiles)",
    "smartmet:schema": "protomaps",
  };
  write(`versatiles-${theme}`, doc);
}

// Meteorological backgrounds

const METEO_LAYERS = [
  "background",
  "earth",
  "landcover",
  "water",
  "water_river",
  "boundaries",
  "boundaries_country",
  "roads_highway",
  "roads_major",
  "water_label_ocean",
  "water_label_lakes",
  "places_region",
  "places_locality",
  "places_country",
];

function set(ls, id, section, prop, value) {
  const l = ls.find((x) => x.id === id);
  if (l) {
    l[section] = l[section] ?? {};
    l[section][prop] = value;
  }
}

function meteo(c) {
  return (ls) => {
    // Borders are important for orientation, roads only faintly visible
    set(ls, "boundaries_country", "paint", "line-color", c.border);
    set(ls, "boundaries_country", "paint", "line-width",
      ["interpolate", ["linear"], ["zoom"], 0, 0.6, 6, 1.0, 10, 1.6]);
    set(ls, "boundaries", "paint", "line-color", c.boundary);
    set(ls, "roads_highway", "paint", "line-width",
      ["interpolate", ["exponential", 1.6], ["zoom"], 5, 0.4, 10, 1.2, 14, 3]);
    ls.find((l) => l.id === "roads_highway").minzoom = 5;
    set(ls, "roads_major", "paint", "line-width",
      ["interpolate", ["exponential", 1.6], ["zoom"], 8, 0.3, 12, 1.0, 16, 3]);
    ls.find((l) => l.id === "roads_major").minzoom = 8;
    set(ls, "landcover", "paint", "fill-opacity", c.landcoverOpacity);
    // One line names: the English name if there is one, the local name otherwise
    for (const l of ls)
      if (l.type === "symbol" && l.layout?.["text-field"])
        l.layout["text-field"] = ["coalesce", ["get", "name:en"], ["get", "name"]];
    return ls.map((l) => ({ ...l, paint: { ...l.paint } }));
  };
}

// Light grey land and pale blue sea, for colourful data such as precipitation
const LIGHT = {
  earth: "#f0efeb",
  water: "#cfdfe8",
  boundary: "#c3c3c3",
  border: "#8c8c8c",
  road: "#e2dcd2",
  label: "#4a4a4a",
  minorlabel: "#8a8a8a",
  countrylabel: "#7a7a7a",
  waterlabel: "#7c94a8",
  halo: "#ffffff",
  landcoverOpacity: 0.35,
  landcover: { ...namedFlavor("light").landcover },
};

// Dark land and sea for radar, satellite and dark user interfaces
const DARK = {
  earth: "#2b2d30",
  water: "#181b20",
  boundary: "#4d5157",
  border: "#868b93",
  road: "#3a3d42",
  label: "#c9cdd3",
  minorlabel: "#8a8f96",
  countrylabel: "#9aa0a8",
  waterlabel: "#5d7387",
  halo: "#16181b",
  landcoverOpacity: 0.25,
  landcover: { ...namedFlavor("dark").landcover },
};

// White land, light grey sea, for print and strongly coloured data
const WHITE = {
  earth: "#ffffff",
  water: "#e3e8ec",
  boundary: "#cfcfcf",
  border: "#9a9a9a",
  road: "#ecebe8",
  label: "#454545",
  minorlabel: "#9a9a9a",
  countrylabel: "#8a8a8a",
  waterlabel: "#8a9aa8",
  halo: "#ffffff",
  landcoverOpacity: 0.0,
  landcover: { ...namedFlavor("white").landcover },
};

for (const [name, base, colors] of [
  ["meteo-light", "light", LIGHT],
  ["meteo-dark", "dark", DARK],
  ["meteo-white", "white", WHITE],
]) {
  const tune = meteo(colors);
  const flavor = {
    ...namedFlavor(base),
    background: colors.water,
    earth: colors.earth,
    water: colors.water,
    boundaries: colors.boundary,
    highway: colors.road,
    major: colors.road,
    city_label: colors.label,
    city_label_halo: colors.halo,
    subplace_label: colors.label,
    subplace_label_halo: colors.halo,
    state_label: colors.minorlabel,
    state_label_halo: colors.halo,
    country_label: colors.countrylabel,
    ocean_label: colors.waterlabel,
    landcover: colors.landcover,
  };
  const title = `Meteorological background, ${base}`;
  const doc = style(name, title, flavor, "en", METEO_LAYERS, tune);
  doc.sprite = `https://protomaps.github.io/basemaps-assets/sprites/v4/${base}`;
  write(name, doc);
}
